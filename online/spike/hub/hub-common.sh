# shellcheck shell=bash
# Shared helpers for the HVN AOE spike hub scripts (WireGuard on Ubuntu 24.04).

HUB_DIR="${AOE_HUB_DIR:-/etc/wireguard}"
IFACE="${AOE_HUB_IFACE:-wg0}"
SUBNET_PREFIX="10.77"
HUB_ADDR="$SUBNET_PREFIX.0.1"
# Endpoint and port only (no secrets), written by setup-hub.sh.
HUB_SETTINGS="$HUB_DIR/aoe-hub-settings"

die() { printf 'LỖI: %s\n' "$*" >&2; exit 1; }
log() { printf '==> %s\n' "$*" >&2; }

require_root() {
  [ "$(id -u)" -eq 0 ] || die "Cần chạy bằng root (sudo)."
}

load_settings() {
  [ -f "$HUB_SETTINGS" ] || die "Chưa dựng hub. Chạy setup-hub.sh trước."
  # shellcheck source=/dev/null
  . "$HUB_SETTINGS"
}

# Rebuild the server config from the interface section and one file per peer,
# so adding or removing a peer never edits wg0.conf by hand.
render_wg_conf() {
  local f
  {
    cat <<CONF
# Generated by HVN AOE setup-hub.sh. Edit peers with add-peer.sh / remove-peer.sh.
[Interface]
Address = $HUB_ADDR/16
ListenPort = $AOE_HUB_PORT
PrivateKey = $(cat "$HUB_DIR/server.key")
PostUp = nft -f $HUB_DIR/aoe-hub.nft
PostDown = nft delete table inet aoe_hub
CONF
    for f in "$HUB_DIR"/peers/*.peer; do
      [ -f "$f" ] || continue
      echo
      cat "$f"
    done
  } > "$HUB_DIR/$IFACE.conf.tmp"
  chmod 600 "$HUB_DIR/$IFACE.conf.tmp"
  mv "$HUB_DIR/$IFACE.conf.tmp" "$HUB_DIR/$IFACE.conf"
}

# Apply peer changes to a running interface without dropping connections.
sync_iface() {
  if wg show "$IFACE" >/dev/null 2>&1; then
    wg syncconf "$IFACE" <(wg-quick strip "$HUB_DIR/$IFACE.conf")
  fi
}
