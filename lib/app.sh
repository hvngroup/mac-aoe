# shellcheck shell=bash
# Building the macOS .app bundle around the toolkit.

AOE_APP_NAME_DEFAULT="AoE RoR"

# make_icon EXE ICNS -> extracts the game's own icon (best effort, macOS only).
make_icon() {
  local exe="$1" icns="$2" work png largest size
  for c in wrestool icotool sips iconutil; do
    command -v "$c" >/dev/null 2>&1 || return 1
  done
  work="$(mktemp -d)"
  wrestool -x -t 14 "$exe" > "$work/app.ico" 2>/dev/null || { rm -rf "$work"; return 1; }
  icotool -x -o "$work" "$work/app.ico" >/dev/null 2>&1 || { rm -rf "$work"; return 1; }
  # shellcheck disable=SC2012  # file names are generated by icotool
  largest="$(ls -S "$work"/*.png 2>/dev/null | head -n 1)"
  [ -n "$largest" ] || { rm -rf "$work"; return 1; }
  mkdir -p "$work/AppIcon.iconset"
  for size in 16 32 128 256 512; do
    png="$work/AppIcon.iconset/icon_${size}x${size}.png"
    sips -z "$size" "$size" "$largest" --out "$png" >/dev/null 2>&1
    sips -z $((size * 2)) $((size * 2)) "$largest" --out "$work/AppIcon.iconset/icon_${size}x${size}@2x.png" >/dev/null 2>&1
  done
  iconutil -c icns "$work/AppIcon.iconset" -o "$icns" >/dev/null 2>&1
  local rc=$?
  rm -rf "$work"
  return $rc
}

cmd_build_app() {
  local out_dir="" name="$AOE_APP_NAME_DEFAULT" root app version zip=0
  while [ $# -gt 0 ]; do
    case "$1" in
      --output) [ $# -ge 2 ] || die "--output cần giá trị"; out_dir="$2"; shift ;;
      --name) [ $# -ge 2 ] || die "--name cần giá trị"; name="$2"; shift ;;
      --zip) zip=1 ;;
      *) die "Tham số không hợp lệ cho build-app: $1" ;;
    esac
    shift
  done
  case "$name" in */*|"") die "Tên app không hợp lệ: $name" ;; esac
  if [ -z "$out_dir" ]; then
    if is_macos; then out_dir="$HOME/Applications"; else out_dir="$(pwd)/app-build"; fi
  fi
  root="$(toolkit_root)"
  version="$(cat "$root/VERSION" 2>/dev/null || echo 0.0.0)"
  app="$out_dir/$name.app"

  log "Tạo ứng dụng: $app"
  mkdir -p "$out_dir"
  rm -rf "$app.tmp"
  mkdir -p "$app.tmp/Contents/MacOS" "$app.tmp/Contents/Resources/toolkit"

  # Embed the toolkit so the app keeps working if this repo is moved/deleted.
  cp "$root/aoe-mac" "$root/VERSION" "$app.tmp/Contents/Resources/toolkit/"
  cp -R "$root/lib" "$root/templates" "$app.tmp/Contents/Resources/toolkit/"

  cp "$root/templates/app-launcher.sh" "$app.tmp/Contents/MacOS/aoe-launcher"
  chmod +x "$app.tmp/Contents/MacOS/aoe-launcher" "$app.tmp/Contents/Resources/toolkit/aoe-mac"

  APP_NAME="$name" APP_VERSION="$version" awk '
    { gsub(/@APP_NAME@/, ENVIRON["APP_NAME"]); gsub(/@VERSION@/, ENVIRON["APP_VERSION"]); print }
  ' "$root/templates/Info.plist.in" > "$app.tmp/Contents/Info.plist"
  printf 'APPL????' > "$app.tmp/Contents/PkgInfo"

  if game_installed && make_icon "$AOE_GAME_DIR/empires.exe" "$app.tmp/Contents/Resources/AppIcon.icns"; then
    log "Đã tạo icon từ empires.exe"
  else
    log "Bỏ qua icon (cần game đã cài + 'brew install icoutils')."
  fi

  rm -rf "$app"
  mv "$app.tmp" "$app"
  if is_macos && command -v codesign >/dev/null 2>&1; then
    # Ad-hoc signature: no Apple ID needed, keeps the bundle structure valid.
    codesign --force --deep --sign - "$app" >/dev/null 2>&1 || warn "Ký ad-hoc thất bại (app vẫn chạy được)."
  fi
  log "Xong. Mở bằng Finder hoặc: open \"$app\""
  if [ "$zip" -eq 1 ]; then
    local zipfile
    zipfile="$out_dir/$(printf '%s' "$name" | tr ' ' '-')-$version-macos.zip"
    rm -f "$zipfile"
    if command -v ditto >/dev/null 2>&1; then
      ditto -c -k --keepParent "$app" "$zipfile" || die "Nén app thất bại."
    else
      need_cmd zip "Cần zip để nén app."
      (cd "$out_dir" && zip -q -r -y "$zipfile" "$name.app") || die "Nén app thất bại."
    fi
    log "Gói gửi người thử: $zipfile"
  fi
}
